-- Косметическая правка ОТКРЫТЫХ позиций (заявка заказчика): цена открытия и
-- плавающая прибыль/убыток на живой позиции не хранятся у нас нигде (это
-- всегда live-данные с брокера) — этой таблицы раньше не было вообще.
-- open_price_override — если задан, live P/L пересчитывается так, как будто
-- позиция открыта по этой цене (текущая цена и объём — настоящие).
-- profit_offset — добавка поверх пересчитанной прибыли: задать конкретное
-- число сейчас, а дальше оно продолжает "плыть" вместе с рынком, не
-- замораживаясь (заявка: "плавающий убыток -200000, поставил -60000, и
-- дальше двигалась без изменения цены входа").
-- Реальная позиция у брокера не трогается — это чисто витрина.
CREATE TABLE IF NOT EXISTS position_overrides (
  ticket BIGINT PRIMARY KEY,
  open_price_override DECIMAL(18, 5),
  profit_offset DECIMAL(18, 2),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
